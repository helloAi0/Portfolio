/**
 * Exports the data of the LOCAL database (DATABASE_URL, e.g. prisma/dev.db) as SQL for Cloudflare D1.
 *   npm run d1:seed-sql                         -> d1-data.sql   (git-ignored)
 *   npx wrangler d1 execute DB --remote --file=d1-data.sql
 * Use it once to move the data you already have locally (repositories, skills, education...) into the live site.
 * Admin accounts, sessions, contact messages' private notes are NOT exported; admin access comes from the Worker secrets.
 */
import { nodePrisma, nodeDbUrl } from './_nodeDb';
import fs from 'fs';
import path from 'path';
import { Prisma } from '@prisma/client';
import { loadModelInfo, parseSchemaModels } from '../src/lib/backupSchema';
import { orderByDependency } from '../src/lib/backup';

const lit = (v: unknown, kind: string): string => {
  if (v === null || v === undefined) return 'NULL';
  if (v instanceof Uint8Array || Buffer.isBuffer(v)) return `X'${Buffer.from(v).toString('hex')}'`;
  if (v instanceof Date) return `'${v.toISOString()}'`;
  if (typeof v === 'boolean') return v ? '1' : '0';
  if (typeof v === 'number' || typeof v === 'bigint') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};

const SKIP = new Set(['AdminUser', 'AdminSession', 'AdminLoginAttempt', 'AdminAuditLog']); // admin access now comes from secrets
const MAX_BLOB = 60_000; // a single D1 statement must stay small; bigger files are re-uploaded in the admin

(async () => {
  const schemaModels = parseSchemaModels(fs.readFileSync(path.join(process.cwd(), 'prisma', 'schema.prisma'), 'utf8'));
  const infos = orderByDependency(loadModelInfo(Prisma));
  const out: string[] = ['-- Data export for Cloudflare D1 (generated by scripts/dump-sql.ts)', 'PRAGMA defer_foreign_keys = true;'];
  let total = 0; const skippedFiles: string[] = []; const empty: string[] = [];
  for (const info of infos) {
    if (SKIP.has(info.name)) continue;
    const model = schemaModels.find((m) => m.name === info.name);
    if (!model) continue;
    const scalar = model.fields.filter((f) => f.kind === 'scalar');
    // Raw SELECT so an older database (fewer or extra columns) still exports; only columns the current schema knows are kept.
    let rows: any[] = [];
    try { rows = await (nodePrisma as any).$queryRawUnsafe(`SELECT * FROM "${info.name}"`); } catch { continue; }
    if (rows.length) empty.push(`${info.name}:${rows.length}`);
    // rows that point at another row of the same table (ProjectCategory.parentId) must come after it
    const done = new Set<string>(); const sorted: any[] = []; let left = [...rows];
    while (left.length) {
      const next = left.filter((r) => !r.parentId || done.has(r.parentId));
      if (!next.length) { sorted.push(...left); break; }
      next.forEach((r) => { done.add(r.id); sorted.push(r); });
      left = left.filter((r) => !next.includes(r));
    }
    for (const r of sorted) {
      const cols = scalar.map((f) => f.name).filter((c) => c in r);
      const vals = cols.map((c) => {
        let v = r[c];
        const f = scalar.find((x) => x.name === c)!;
        if (f.type === 'DateTime' && typeof v === 'number') v = new Date(v).toISOString();
        if (f.type === 'DateTime' && typeof v === 'bigint') v = new Date(Number(v)).toISOString();
        if (info.name === 'StoredFile' && c === 'data' && v && (v as Uint8Array).byteLength > MAX_BLOB) { skippedFiles.push(String(r.filename || r.id)); v = null; }
        return lit(v, '');
      });
      out.push(`INSERT OR REPLACE INTO "${info.name}" (${cols.map((c) => `"${c}"`).join(', ')}) VALUES (${vals.join(', ')});`);
      total++;
    }
  }
  fs.writeFileSync('d1-data.sql', out.join('\n') + '\n');
  console.log(`Wrote d1-data.sql with ${total} rows from ${nodeDbUrl}`);
  console.log(`Rows per table: ${empty.join(', ') || 'none (the database is empty)'}`);
  if (skippedFiles.length) console.log(`Re-upload these large files in the admin (too big to copy as SQL): ${skippedFiles.join(', ')}`);
  await nodePrisma.$disconnect();
})().catch((e) => { console.error('Export failed:', e.message); process.exit(1); });
