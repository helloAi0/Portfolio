/**
 * Exports the data of the LOCAL database (DATABASE_URL, e.g. prisma/dev.db) as SQL for Cloudflare D1.
 *   npm run d1:seed-sql                         -> d1-data.sql   (git-ignored)
 *   npx wrangler d1 execute DB --remote --file=d1-data.sql
 * Use it once to move the data you already have locally (repositories, skills, education...) into the live site.
 * Admin accounts, sessions, contact messages' private notes are NOT exported; admin access comes from the Worker secrets.
 */
import { nodePrisma, nodeDbUrl } from './_nodeDb';
import fs from 'fs';
import { Prisma } from '@prisma/client';
import { loadModelInfo } from '../src/lib/backupSchema';
import { orderByDependency } from '../src/lib/backup';

const lit = (v: unknown, kind: string): string => {
  if (v === null || v === undefined) return 'NULL';
  if (v instanceof Uint8Array || Buffer.isBuffer(v)) return `X'${Buffer.from(v).toString('hex')}'`;
  if (v instanceof Date) return `'${v.toISOString()}'`;
  if (typeof v === 'boolean') return v ? '1' : '0';
  if (typeof v === 'number' || typeof v === 'bigint') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};

(async () => {
  const infos = orderByDependency(loadModelInfo(Prisma));
  const out: string[] = ['-- Data export for Cloudflare D1 (generated by scripts/dump-sql.ts)', 'PRAGMA defer_foreign_keys = true;'];
  let total = 0;
  for (const info of infos) {
    const rows: any[] = await (nodePrisma as any)[info.name.charAt(0).toLowerCase() + info.name.slice(1)].findMany();
    // rows that point at another row of the same table (ProjectCategory.parentId) must come after it
    const done = new Set<string>(); const sorted: any[] = []; let left = [...rows];
    while (left.length) {
      const next = left.filter((r) => !r.parentId || done.has(r.parentId));
      if (!next.length) { sorted.push(...left); break; }
      next.forEach((r) => { done.add(r.id); sorted.push(r); });
      left = left.filter((r) => !next.includes(r));
    }
    for (const r of sorted) {
      const cols = Object.keys(r);
      out.push(`INSERT OR REPLACE INTO "${info.name}" (${cols.map((c) => `"${c}"`).join(', ')}) VALUES (${cols.map((c) => lit(r[c], '')).join(', ')});`);
      total++;
    }
  }
  fs.writeFileSync('d1-data.sql', out.join('\n') + '\n');
  console.log(`Wrote d1-data.sql with ${total} rows from ${nodeDbUrl}`);
  await nodePrisma.$disconnect();
})().catch((e) => { console.error('Export failed:', e.message); process.exit(1); });
