#!/usr/bin/env node
/**
 * Generates the SQLite DDL for Cloudflare D1 straight from prisma/schema.prisma (no database or engine download needed).
 *   node scripts/gen-d1-migration.mjs            -> writes migrations/0001_init.sql
 *   node scripts/gen-d1-migration.mjs --check    -> exits 1 if the committed file is out of date
 * For later schema changes, add a new numbered file (see deploy/cloudflare.md).
 */
import fs from 'fs';
import internals from '@prisma/internals';
const { getDMMF } = internals;

const T = { String: 'TEXT', Int: 'INTEGER', BigInt: 'BIGINT', Float: 'REAL', Boolean: 'BOOLEAN', DateTime: 'DATETIME', Json: 'JSONB', Bytes: 'BLOB', Decimal: 'DECIMAL' };
const q = (s) => `"${s}"`;
const act = { Cascade: 'CASCADE', SetNull: 'SET NULL', Restrict: 'RESTRICT', NoAction: 'NO ACTION', SetDefault: 'SET DEFAULT' };

const dmmf = await getDMMF({ datamodel: fs.readFileSync('prisma/schema.prisma', 'utf8') });
const models = dmmf.datamodel.models;
const out = ['-- Generated by scripts/gen-d1-migration.mjs from prisma/schema.prisma. Do not edit by hand.', ''];
const idx = [];

for (const m of models) {
  const cols = [], tail = [];
  const scalars = m.fields.filter((f) => f.kind === 'scalar' || f.kind === 'enum');
  for (const f of scalars) {
    if (f.isList) throw new Error(`Scalar lists are not supported on SQLite (${m.name}.${f.name})`);
    let c = `${q(f.name)} ${T[f.type] ?? 'TEXT'}`;
    const singlePk = f.isId && !m.primaryKey;
    if (singlePk) c += f.default?.name === 'autoincrement' ? ' PRIMARY KEY AUTOINCREMENT' : ' PRIMARY KEY';
    if (f.isRequired || singlePk) c += ' NOT NULL';
    if (f.hasDefaultValue && f.default !== undefined) {
      const d = f.default;
      if (typeof d === 'string') c += ` DEFAULT '${d.replace(/'/g, "''")}'`;
      else if (typeof d === 'number') c += ` DEFAULT ${d}`;
      else if (typeof d === 'boolean') c += ` DEFAULT ${d ? 1 : 0}`;
      else if (d.name === 'now') c += ' DEFAULT CURRENT_TIMESTAMP';
      // cuid()/uuid() are generated by the Prisma client, not by the database
    }
    cols.push(c);
  }
  if (m.primaryKey) tail.push(`PRIMARY KEY (${m.primaryKey.fields.map(q).join(', ')})`);
  for (const f of m.fields.filter((x) => x.kind === 'object' && x.relationFromFields?.length)) {
    const onDelete = act[f.relationOnDelete] ?? (f.isRequired ? 'RESTRICT' : 'SET NULL');
    tail.push(`FOREIGN KEY (${f.relationFromFields.map(q).join(', ')}) REFERENCES ${q(f.type)}(${f.relationToFields.map(q).join(', ')}) ON DELETE ${onDelete} ON UPDATE CASCADE`);
  }
  out.push(`CREATE TABLE ${q(m.name)} (\n  ${[...cols, ...tail].join(',\n  ')}\n);`, '');
}

for (const i of dmmf.datamodel.indexes) {
  if (i.type === 'id') continue;
  const names = i.fields.map((f) => f.name);
  if (i.type === 'unique') idx.push(`CREATE UNIQUE INDEX ${q(`${i.model}_${names.join('_')}_key`)} ON ${q(i.model)}(${names.map(q).join(', ')});`);
  else if (i.type === 'normal') idx.push(`CREATE INDEX ${q(`${i.model}_${names.join('_')}_idx`)} ON ${q(i.model)}(${names.map(q).join(', ')});`);
}
out.push(...idx, '');
const sql = out.join('\n');

if (process.argv.includes('--check')) {
  // 0001 is the frozen baseline; later files (0002_...) add columns. Together they must cover every model and column.
  const files = fs.existsSync('migrations') ? fs.readdirSync('migrations').filter((f) => f.endsWith('.sql')).sort() : [];
  const all = files.map((f) => fs.readFileSync(`migrations/${f}`, 'utf8')).join('\n');
  const missing = [];
  for (const m of models) {
    if (!all.includes(`CREATE TABLE ${q(m.name)} (`)) { missing.push(`table ${m.name}`); continue; }
    const body = all.slice(all.indexOf(`CREATE TABLE ${q(m.name)} (`)).split('\n);')[0];
    for (const f of m.fields.filter((x) => x.kind === 'scalar' || x.kind === 'enum')) {
      const added = new RegExp(`ALTER TABLE ${q(m.name)} ADD COLUMN ${q(f.name)} `).test(all);
      if (!body.includes(`${q(f.name)} `) && !added) missing.push(`${m.name}.${f.name}`);
    }
  }
  if (missing.length) { console.error(`Migrations are out of date (missing: ${missing.join(', ')}). Add migrations/000N_<name>.sql; "npm run d1:migration" prints the full current schema for reference.`); process.exit(1); }
  console.log(`Migrations (${files.join(', ')}) cover the current Prisma schema.`);
} else if (process.argv.includes('--write-baseline')) {
  fs.mkdirSync('migrations', { recursive: true });
  fs.writeFileSync('migrations/0001_init.sql', sql);
  console.log(`Wrote migrations/0001_init.sql (${models.length} tables, ${idx.length} indexes)`);
} else {
  console.log(sql);
}
