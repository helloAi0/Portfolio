/**
 * Finds and removes leftovers from the original template and old test runs ("Sahil Depurwala", Macedon-Vision, CipherSentinel,
 * Aethelgard, "Neuromorphic Microcode ..." test questions) that live in YOUR DATABASE (not in the code).
 *
 *   npm run data:clean-legacy            -> only reports what it finds (changes nothing)
 *   npm run data:clean-legacy -- --apply -> deletes the leftovers and resets the profile bio to a factual line
 * It also writes legacy-clean.sql (git-ignored) for the live Cloudflare database:
 *   npx wrangler d1 execute DB --remote --file=legacy-clean.sql
 */
import { nodePrisma, nodeDbUrl } from './_nodeDb';
import fs from 'fs';
import { PROFILE } from '../src/config/profile';

const MARK = ['sahil', 'depurwala', 'macedon-vision', 'aethelgard', 'ciphersentinel', 'neuromorphic microcode', 'neuromorphic spiking'];
const BIO_MARK = ['monumentality', 'forward conquest', 'imperial software', 'foundational excellence'];
const db = nodePrisma as any; const apply = process.argv.includes('--apply');
const like = (cols: string[]) => cols.map((c) => MARK.map((m) => `LOWER("${c}") LIKE '%${m}%'`).join(' OR ')).join(' OR ');
const TARGETS: { table: string; cols: string[]; label: string }[] = [
  { table: 'UnansweredQuestion', cols: ['question', 'context', 'ownerAnswer'], label: 'LAMO inbox questions' },
  { table: 'BiographyReview', cols: ['currentBio', 'proposedBio', 'reasons'], label: 'Biography proposals' },
  { table: 'AiKnowledgeRecord', cols: ['topic', 'content'], label: 'LAMO knowledge records' },
  { table: 'LamoMessage', cols: ['content'], label: 'LAMO chat messages' },
  { table: 'Project', cols: ['title', 'slug', 'tagline', 'description'], label: 'Projects' },
];
const bioFor = () => `${PROFILE.displayName} is pursuing a ${PROFILE.education.degree} in ${PROFILE.education.field}${PROFILE.education.minor ? ` with a minor in ${PROFILE.education.minor}` : ''}${PROFILE.education.institution ? ` at ${PROFILE.education.institution}` : ''}.`;

(async () => {
  console.log(`Database: ${nodeDbUrl}\nMode: ${apply ? 'APPLY (deleting)' : 'report only'}\n`);
  const sql: string[] = ['-- Removes template / test leftovers. Generated by scripts/clean-legacy-data.ts'];
  let total = 0;
  for (const t of TARGETS) {
    let rows: any[] = [];
    try { rows = await db.$queryRawUnsafe(`SELECT id, ${t.cols.map((c) => `"${c}"`).join(', ')} FROM "${t.table}" WHERE ${like(t.cols)}`); } catch { continue; }
    console.log(`${t.label}: ${rows.length} found`);
    rows.slice(0, 5).forEach((r) => console.log('   -', String(r[t.cols[0]]).slice(0, 90)));
    total += rows.length;
    if (t.table === 'Project') { sql.push(`DELETE FROM "ProjectSkill" WHERE "projectId" IN (SELECT id FROM "Project" WHERE ${like(t.cols)});`); }
    sql.push(`DELETE FROM "${t.table}" WHERE ${like(t.cols)};`);
    if (apply && rows.length) {
      if (t.table === 'Project') { try { await db.$executeRawUnsafe(`DELETE FROM "ProjectSkill" WHERE "projectId" IN (SELECT id FROM "Project" WHERE ${like(t.cols)})`); } catch { /* table may differ */ } }
      await db.$executeRawUnsafe(`DELETE FROM "${t.table}" WHERE ${like(t.cols)}`);
    }
  }
  // The live profile record: reset name/contact fields to the single source of truth, and the bio if it is the old template text.
  const prof = (await db.$queryRawUnsafe(`SELECT id, displayName, bio, contactEmail FROM "Profile" LIMIT 1`).catch(() => []))[0];
  if (prof) {
    const badBio = [...MARK, ...BIO_MARK].some((m) => String(prof.bio).toLowerCase().includes(m)) || [...MARK].some((m) => String(prof.displayName).toLowerCase().includes(m));
    console.log(`Profile: name "${prof.displayName}", bio ${badBio ? 'is OLD TEMPLATE TEXT' : 'looks fine'}`);
    if (badBio) { total++; if (apply) await db.$executeRawUnsafe(`UPDATE "Profile" SET displayName = ?, contactEmail = ?, bio = ?, headline = ?, location = ? WHERE id = ?`, PROFILE.displayName, PROFILE.contactEmail, bioFor(), PROFILE.headline, PROFILE.location, prof.id); }
    sql.push(`UPDATE "Profile" SET "displayName" = '${PROFILE.displayName.replace(/'/g, "''")}', "bio" = '${bioFor().replace(/'/g, "''")}' WHERE LOWER("bio") LIKE '%monumentality%' OR LOWER("bio") LIKE '%foundational excellence%' OR LOWER("displayName") LIKE '%sahil%';`);
  }
  fs.writeFileSync('legacy-clean.sql', sql.join('\n') + '\n');
  console.log(`\n${total} item(s) ${apply ? 'cleaned' : 'found. Run again with --apply to remove them'}. Wrote legacy-clean.sql for the live database.`);
  await nodePrisma.$disconnect();
})().catch((e) => { console.error('Failed:', e.message); process.exit(1); });
